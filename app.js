// ============================================================
//  1. MODEL BACKEND CONFIGURATION
// ============================================================
// Point this to your backend server endpoint (FastAPI, Flask, Gradio, etc.)
// By default, it connects to a local /api/chat endpoint.
const MODEL_API_ENDPOINT = '/api/chat';

/**
 * Query your AI model backend.
 * @param {string} userMessage - Text message entered by the user.
 * @param {string} userName    - User's name from the welcome screen.
 * @returns {Promise<string>}  - Reply text generated by your model.
 */
async function callModelAPI(userMessage, userName) {
  try {
    const res = await fetch(MODEL_API_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: userMessage,
        user_name: userName
      })
    });

    if (!res.ok) {
      throw new Error(`Server returned HTTP ${res.status}`);
    }

    const data = await res.json();
    // Accommodates common response payload shapes:
    // { "reply": "..." } or { "response": "..." } or { "message": "..." }
    return data.reply || data.response || data.message || (Array.isArray(data) ? data[0] : JSON.stringify(data));
  } catch (error) {
    console.warn('Model backend offline or unreachable:', error);
    return `(Model Offline) Connect your backend server at ${MODEL_API_ENDPOINT} to chat with your model. Received: "${userMessage}"`;
  }
}

// ============================================================
//  2. UI STATE & DOM REFS
// ============================================================
const state = {
  userName: '',
  currentScreen: 'welcome',
  isTyping: false,
  firstMessage: true,
  sparkleMenuOpen: false
};

const screens = {
  welcome: document.getElementById('screen-welcome'),
  chat:    document.getElementById('screen-chat')
};

// Welcome
const nameInput = document.getElementById('name-input');
const nameForm  = document.getElementById('name-form');
const nameBtn   = document.getElementById('name-btn');

// Chat
const chatMessages     = document.getElementById('chat-messages');
const chatInput        = document.getElementById('chat-input');
const sendBtn          = document.getElementById('send-btn');
const typingIndicator  = document.getElementById('typing-indicator');
const topicsSection    = document.getElementById('topics-section');
const chatHeader       = document.getElementById('chat-header');
const chatBotTagline   = document.getElementById('chat-bot-tagline');
const chatBotName      = document.getElementById('chat-bot-name');
const chatHeaderCenter = document.getElementById('chat-header-center');

// ============================================================
//  3. INITIALIZATION
// ============================================================
function init() {
  localStorage.removeItem('lovey_username');
  goToScreen('welcome', true);
  startAmbientParticles('screen-welcome');
  bindEvents();
}

function clearChatForFreshStart() {
  Array.from(chatMessages.children).forEach(child => {
    if (child.id !== 'topics-section' && child.id !== 'typing-indicator') {
      child.remove();
    }
  });
  if (topicsSection) {
    topicsSection.classList.remove('hidden-fade');
    topicsSection.style.visibility = '';
  }
  expandHeader();
  state.firstMessage = true;
}

// ============================================================
//  4. SCREEN ROUTER
// ============================================================
async function goToScreen(target, instant = false) {
  const current = screens[state.currentScreen];
  const next    = screens[target];

  if (state.currentScreen === target) return;

  stopAmbientParticles();

  if (instant) {
    Object.values(screens).forEach(s => {
      s.style.display = 'none';
      s.style.opacity = '0';
    });
    next.style.display = 'flex';
    next.style.opacity = '1';
    next.style.transform = 'scale(1)';
  } else {
    await fadeOut(current, 450);
    current.style.display = 'none';
    await fadeIn(next, 450);
  }

  state.currentScreen = target;

  if (target === 'welcome') {
    startAmbientParticles('screen-welcome');
    nameInput.value = '';
    nameInput.focus();
  }

  if (target === 'chat') {
    startAmbientParticles('screen-chat');
    chatInput.focus();
  }
}

function saveName(name) {
  state.userName = name.trim();
  localStorage.setItem('lovey_username', state.userName);
}

// ============================================================
//  5. WELCOME FLOW
// ============================================================
function handleNameSubmit(e) {
  e?.preventDefault();
  const name = nameInput.value.trim();
  if (!name) {
    nameInput.classList.add('shake');
    setTimeout(() => nameInput.classList.remove('shake'), 500);
    return;
  }
  saveName(name);
  welcomeHeartBurst();
  setTimeout(() => {
    goToScreen('chat');
    setTimeout(() => {
      addBotMessage(`Hi ${state.userName}!! 💕 I'm so happy you're here! How can I help you today? I have been waiting for you~ 🌸`);
    }, 600);
  }, 900);
}

// ============================================================
//  6. CHAT HELPERS & MESSAGES
// ============================================================
function addBotMessage(text) {
  if (!chatMessages) return;
  const wrapper = document.createElement('div');
  wrapper.classList.add('message-wrapper', 'bot-wrapper');

  const avatar = document.createElement('div');
  avatar.classList.add('bot-avatar-dot');
  const img = document.createElement('img');
  img.src = 'Shruti.jpeg';
  img.alt = 'Sruthi';
  img.classList.add('avatar-img');
  avatar.appendChild(img);

  const bubble = document.createElement('div');
  bubble.classList.add('message-bubble', 'bot-bubble');
  bubble.textContent = text;

  wrapper.appendChild(avatar);
  wrapper.appendChild(bubble);
  chatMessages.appendChild(wrapper);
  revealMessage(wrapper, 'left');
  scrollToBottom();
}

function addUserMessage(text) {
  if (!chatMessages) return;
  if (state.firstMessage) {
    hideQuickContent();
    state.firstMessage = false;
  }
  const wrapper = document.createElement('div');
  wrapper.classList.add('message-wrapper', 'user-wrapper');

  const bubble = document.createElement('div');
  bubble.classList.add('message-bubble', 'user-bubble');
  bubble.textContent = text;

  wrapper.appendChild(bubble);
  chatMessages.appendChild(wrapper);
  revealMessage(wrapper, 'right');
  scrollToBottom();
}

function showTypingIndicator() {
  if (typingIndicator) { typingIndicator.style.display = 'flex'; scrollToBottom(); }
}

function hideTypingIndicator() {
  if (typingIndicator) typingIndicator.style.display = 'none';
}

function scrollToBottom() {
  requestAnimationFrame(() => {
    chatMessages.scrollTo({ top: chatMessages.scrollHeight, behavior: 'smooth' });
  });
}

function hideQuickContent() {
  if (topicsSection) topicsSection.classList.add('hidden-fade');
  collapseHeader();
}

function collapseHeader() {
  if (chatHeaderCenter) chatHeaderCenter.classList.add('header-left');
  if (chatBotTagline)   chatBotTagline.classList.add('tagline-hidden');
}

function expandHeader() {
  if (chatHeaderCenter) chatHeaderCenter.classList.remove('header-left');
  if (chatBotTagline)   chatBotTagline.classList.remove('tagline-hidden');
}

// ============================================================
//  7. SEND MESSAGE FLOW (CONNECTED TO MODEL)
// ============================================================
async function sendMessage(text) {
  const trimmed = text.trim();
  if (!trimmed || state.isTyping) return;

  addUserMessage(trimmed);
  heartBurst(sendBtn);
  chatInput.value = '';
  chatInput.style.height = 'auto';

  state.isTyping = true;
  showTypingIndicator();

  // Query the AI Model
  const reply = await callModelAPI(trimmed, state.userName);

  hideTypingIndicator();
  addBotMessage(reply);
  state.isTyping = false;
}

function handleReset() {
  localStorage.removeItem('lovey_username');
  state.userName      = '';
  state.firstMessage  = true;
  state.sparkleMenuOpen = false;
  Array.from(chatMessages.children).forEach(child => {
    if (child.id !== 'topics-section' && child.id !== 'typing-indicator') child.remove();
  });
  if (topicsSection) topicsSection.classList.remove('hidden-fade');
  expandHeader();
  goToScreen('welcome');
}

// ============================================================
//  8. TOPIC CARDS (PROMPTS CONNECTED TO MODEL)
// ============================================================
function handleTopic(topicKey) {
  const topicPrompts = {
    loveletter: 'Write me a heartfelt, romantic love letter 💕',
    crush: "Let's talk about my crush! I want to tell you everything 🥰",
    flirt: 'Flirt with me playfully 😘',
    romance: 'Set the romantic vibes with soft words and sweet poetry 🌹'
  };

  const prompt = topicPrompts[topicKey] || topicKey;
  sendMessage(prompt);
}

// ============================================================
//  9. EVENT BINDINGS
// ============================================================
function bindEvents() {
  // Welcome form
  nameForm?.addEventListener('submit', handleNameSubmit);
  nameBtn?.addEventListener('click', handleNameSubmit);
  nameInput?.addEventListener('keydown', (e) => {
    if (e.key === 'Enter') handleNameSubmit(e);
  });

  // Chat send
  sendBtn?.addEventListener('click', () => sendMessage(chatInput.value));
  chatInput?.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      sendMessage(chatInput.value);
    }
  });

  // Auto-resize textarea
  chatInput?.addEventListener('input', () => {
    chatInput.style.height = 'auto';
    chatInput.style.height = Math.min(chatInput.scrollHeight, 120) + 'px';
  });

  document.getElementById('menu-reset')?.addEventListener('click', handleReset);

  // Romantic topic cards
  document.querySelectorAll('.topic-card').forEach(card => {
    card.addEventListener('click', () => handleTopic(card.dataset.topic));
    card.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); card.click(); }
    });
  });

  // Input glow
  if (chatInput) attachInputGlow(chatInput);
  if (nameInput) attachInputGlow(nameInput);

  // Shimmer on hover
  document.querySelectorAll('.shimmer-btn').forEach(btn => {
    btn.addEventListener('mouseenter', () => addShimmer(btn));
  });

  document.getElementById('menu-reset')?.addEventListener('keydown', (e) => {
    if (e.key === 'Enter') document.getElementById('menu-reset').click();
  });
}

// ── Boot ─────────────────────────────────────────────────────
document.addEventListener('DOMContentLoaded', init);
